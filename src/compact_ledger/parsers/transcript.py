"""Transcript readers for Claude Code, Codex, and generic JSONL transcripts."""

from __future__ import annotations

import json
import re
import shlex
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

from compact_ledger.models import (
    VALID_FILE_OPERATIONS,
    FileEdit,
    FileOperation,
    ParsedTranscript,
    ToolExecution,
    UserTurn,
    sanitize_unicode,
)

SUPPORTED_FORMATS: frozenset[str] = frozenset({"auto", "claude-code", "codex", "generic"})

_CODEX_WRAPPER_TYPES = frozenset(
    {
        "session_meta",
        "response_item",
        "event_msg",
        "turn_context",
        "function_call",
        "function_call_output",
        "custom_tool_call",
        "custom_tool_call_output",
        "local_shell_call",
        "local_shell_call_output",
    }
)
_CLAUDE_ENTRY_TYPES = frozenset(
    {"user", "assistant", "system", "summary", "progress", "file-history-snapshot"}
)
_SHELL_TOOL_NAMES = frozenset(
    {"bash", "shell", "shell_command", "exec_command", "local_shell", "container.exec"}
)

_ASCII_INT_RE = re.compile(r"-?[0-9]{1,18}")
_HEADER_EXIT_CODE_RE = re.compile(
    r"^(?:Exit code[:\s]+|Command exited with (?:non-zero )?status\s+|Process exited with code\s+)"
    r"(-?[0-9]{1,9})\b",
    re.IGNORECASE,
)
_CODEX_HEADER_PREFIXES = (
    "Chunk ID:",
    "Wall time:",
    "Process exited with code ",
    "Exit code:",
    "Original token count:",
)
# Harness-authored text that Claude Code records with role "user". None of it is something
# the human typed, so it must never become a user constraint.
_CLAUDE_NOISE_PREFIXES = (
    "[Request interrupted by user",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
)
_CLAUDE_WRAPPER_TAG_RE = re.compile(
    r"^\s*<(?:command-name|command-message|command-args|command-stdout|command-stderr|"
    r"local-command-stdout|local-command-stderr|local-command-caveat|task-notification|"
    r"system-reminder|bash-input|bash-stdout|bash-stderr|user-prompt-submit-hook|"
    r"user-memory-input|background-task-output|teammate-message)[ >]"
)
# "Stop hook feedback:", "PreToolUse:Bash hook blocking error from command: ...", etc.
_CLAUDE_HOOK_FEEDBACK_RE = re.compile(
    r"^[A-Za-z]+(?::[A-Za-z_*|.-]{1,60})? hook "
    r"(?:feedback|blocking error|error|additional context|stopped continuation)\b",
)
_SYSTEM_REMINDER_OPEN = "<system-reminder>"
_SYSTEM_REMINDER_CLOSE = "</system-reminder>"
_CODEX_HARNESS_PREFIXES = (
    "<environment_context>",
    "# AGENTS.md instructions",
    "<INSTRUCTIONS>",
    "<user_instructions>",
    "<turn_aborted>",
    "<subagent_notification>",
    "Background command completed (exit ",
)
_BEGIN_PATCH_MARKER = "*** Begin Patch"
_END_PATCH_MARKER = "*** End Patch"


def _as_str(value: Any) -> str | None:
    return sanitize_unicode(value) if isinstance(value, str) else None


def _as_int(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        stripped = value.strip()
        if _ASCII_INT_RE.fullmatch(stripped):
            return int(stripped)
    return None


def _add_modified_file(modified_files: list[str], seen: set[str], path: str | None) -> None:
    if not path:
        return
    cleaned = path.strip()
    if cleaned and cleaned not in seen:
        seen.add(cleaned)
        modified_files.append(cleaned)


def _extract_text_from_content(content: Any) -> str:
    """Extract joined text from a string or list of content blocks."""
    if isinstance(content, str):
        return sanitize_unicode(content)
    if isinstance(content, list):
        parts: list[str] = []
        for block in content:
            if isinstance(block, str):
                parts.append(sanitize_unicode(block))
            elif isinstance(block, dict):
                btype = block.get("type")
                if btype in ("text", "input_text", "output_text", None):
                    text = block.get("text")
                    if isinstance(text, str):
                        parts.append(sanitize_unicode(text))
        return "\n".join(parts)
    return ""


def _extract_exit_code_from_first_line(text: str) -> int | None:
    """Extract an exit code strictly from the first line (O(1), no body scan)."""
    if not text:
        return None
    first_line = text.split("\n", 1)[0].strip()
    match = _HEADER_EXIT_CODE_RE.match(first_line)
    if match:
        return int(match.group(1))
    return None


def _format_command_arg(cmd: Any) -> str | None:
    if isinstance(cmd, str):
        return sanitize_unicode(cmd)
    if isinstance(cmd, list) and all(isinstance(part, str) for part in cmd) and cmd:
        clean_parts = [sanitize_unicode(part) for part in cmd]
        if (
            len(clean_parts) == 3
            and clean_parts[0] in ("bash", "sh", "zsh", "/bin/bash", "/bin/sh", "/bin/zsh")
            and clean_parts[1] in ("-c", "-lc")
        ):
            return clean_parts[2]
        if (
            len(clean_parts) == 4
            and clean_parts[0] in ("env", "/usr/bin/env")
            and clean_parts[1] in ("bash", "sh", "zsh")
            and clean_parts[2] in ("-c", "-lc")
        ):
            return clean_parts[3]
        return shlex.join(clean_parts)
    return None


def _extract_patch_from_shell_command(raw_cmd: Any, formatted_cmd: str | None) -> str | None:
    """Detect ``apply_patch`` invoked via a shell command or argv list."""
    if (
        isinstance(raw_cmd, list)
        and len(raw_cmd) >= 2
        and isinstance(raw_cmd[0], str)
        and Path(raw_cmd[0]).name == "apply_patch"
        and isinstance(raw_cmd[1], str)
    ):
        return sanitize_unicode(raw_cmd[1])

    if formatted_cmd and _BEGIN_PATCH_MARKER in formatted_cmd:
        start = formatted_cmd.find(_BEGIN_PATCH_MARKER)
        end = formatted_cmd.find(_END_PATCH_MARKER, start)
        if end != -1:
            return formatted_cmd[start : end + len(_END_PATCH_MARKER)]
        return formatted_cmd[start:]
    return None


def _parse_apply_patch(
    patch_text: str,
    *,
    turn_index: int,
    timestamp: str | None,
    call_id: str | None = None,
    next_seq: Any = None,
) -> tuple[list[FileEdit], list[str]]:
    """Parse Codex ``apply_patch`` format into contiguous ``FileEdit`` records."""
    edits: list[FileEdit] = []
    extra_paths: list[str] = []
    seen_extra: set[str] = set()

    current_path: str | None = None
    current_op: FileOperation | None = None
    old_lines: list[str] = []
    new_lines: list[str] = []
    emitted_hunk_for_file = False

    def _emit_hunk(*, force: bool = False) -> None:
        nonlocal old_lines, new_lines, emitted_hunk_for_file
        if current_path is None or current_op is None:
            return
        if not force and not old_lines and not new_lines:
            return
        seq_val = next_seq() if callable(next_seq) else 0
        edits.append(
            FileEdit(
                turn_index=turn_index,
                path=current_path,
                operation=current_op,
                old_text="\n".join(old_lines) if old_lines else None,
                new_text="\n".join(new_lines) if new_lines else None,
                timestamp=timestamp,
                call_id=call_id,
                seq=seq_val,
            )
        )
        old_lines = []
        new_lines = []
        emitted_hunk_for_file = True

    def _flush_file() -> None:
        nonlocal current_path, current_op, old_lines, new_lines, emitted_hunk_for_file
        if (
            current_path is not None
            and current_op is not None
            and (not emitted_hunk_for_file or old_lines or new_lines)
        ):
            _emit_hunk(force=not emitted_hunk_for_file)
        current_path = None
        current_op = None
        old_lines = []
        new_lines = []
        emitted_hunk_for_file = False

    normalized_text = sanitize_unicode(patch_text).replace("\r\n", "\n")
    for line in normalized_text.split("\n"):
        if line.startswith("*** Update File:"):
            _flush_file()
            current_path = line.split(":", 1)[1].strip()
            current_op = "edit"
        elif line.startswith("*** Add File:"):
            _flush_file()
            current_path = line.split(":", 1)[1].strip()
            current_op = "write"
        elif line.startswith("*** Delete File:"):
            _flush_file()
            current_path = line.split(":", 1)[1].strip()
            current_op = "delete"
        elif line.startswith("*** Move to:"):
            if current_path is not None:
                _add_modified_file(extra_paths, seen_extra, current_path)
                moved = line.split(":", 1)[1].strip()
                if moved:
                    current_path = moved
        elif line.startswith(_END_PATCH_MARKER) or line.startswith("*** End of File"):
            _flush_file()
        elif line.startswith("@@"):
            if current_op == "edit" and (old_lines or new_lines):
                _emit_hunk(force=False)
        elif current_op is not None:
            # In Codex apply_patch format, every '+'/'-' line inside a file section is
            # real content (never unified-diff '+++'/'---' file headers).
            if line.startswith("+"):
                new_lines.append(line[1:])
            elif line.startswith("-"):
                old_lines.append(line[1:])

    _flush_file()
    return edits, extra_paths


def _iter_json_records(lines: Iterable[str]) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    first = True
    for raw_line in lines:
        if first:
            first = False
            if raw_line.startswith("\ufeff"):
                raw_line = raw_line[1:]
        stripped = raw_line.strip()
        if not stripped:
            continue
        try:
            parsed = json.loads(stripped)
        except (json.JSONDecodeError, ValueError, RecursionError):
            continue
        if isinstance(parsed, dict):
            records.append(parsed)
    return records


def detect_transcript_format(records: Sequence[dict[str, Any]]) -> str:
    """Detect whether parsed JSONL records are Claude Code, Codex, or generic."""
    if not records:
        return "unknown"

    codex_score = 0
    claude_score = 0
    generic_score = 0

    for record in records[:100]:
        rec_type = record.get("type")
        if isinstance(rec_type, str) and rec_type in _CODEX_WRAPPER_TYPES:
            codex_score += 3
            continue

        if (
            isinstance(rec_type, str)
            and rec_type in _CLAUDE_ENTRY_TYPES
            and (
                isinstance(record.get("message"), dict)
                or "sessionId" in record
                or "parentUuid" in record
                or "toolUseResult" in record
                or rec_type in ("summary", "file-history-snapshot")
            )
        ):
            claude_score += 3
            continue

        if isinstance(record.get("message"), dict):
            content = record["message"].get("content")
            if isinstance(content, list) and any(
                isinstance(b, dict) and b.get("type") in ("tool_use", "tool_result")
                for b in content
            ):
                claude_score += 3
                continue

        if (
            "role" in record
            or "command" in record
            or rec_type in ("file_edit", "tool", "tool_execution", "command")
        ):
            generic_score += 1

    if codex_score > 0 and codex_score >= claude_score:
        return "codex"
    if claude_score > 0:
        return "claude-code"
    if generic_score > 0:
        return "generic"
    return "generic"


def _strip_system_reminders(text: str) -> str:
    """Remove ``<system-reminder>...</system-reminder>`` spans in O(N).

    Claude Code appends reminders to genuine user messages; an unclosed tag drops the rest.
    """
    if _SYSTEM_REMINDER_OPEN not in text:
        return text
    parts: list[str] = []
    pos = 0
    while True:
        start = text.find(_SYSTEM_REMINDER_OPEN, pos)
        if start == -1:
            parts.append(text[pos:])
            break
        parts.append(text[pos:start])
        end = text.find(_SYSTEM_REMINDER_CLOSE, start)
        if end == -1:
            break
        pos = end + len(_SYSTEM_REMINDER_CLOSE)
    return "".join(parts).strip()


def _is_claude_noise_user_text(text: str) -> bool:
    if text.startswith(_CLAUDE_NOISE_PREFIXES):
        return True
    if _CLAUDE_HOOK_FEEDBACK_RE.match(text):
        return True
    return bool(_CLAUDE_WRAPPER_TAG_RE.match(text))


def _is_codex_harness_user_text(text: str) -> bool:
    return text.startswith(_CODEX_HARNESS_PREFIXES)


def _extract_claude_file_edits(
    tool_name: str,
    tool_input: dict[str, Any],
    *,
    turn_index: int,
    timestamp: str | None,
    call_id: str | None,
    next_seq: Any,
) -> list[FileEdit]:
    edits: list[FileEdit] = []
    if tool_name == "Edit":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        if path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="edit",
                    old_text=_as_str(tool_input.get("old_string")),
                    new_text=_as_str(tool_input.get("new_string")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "Write":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        if path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="write",
                    old_text=None,
                    new_text=_as_str(tool_input.get("content")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "MultiEdit":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        raw_edits = tool_input.get("edits")
        if path and isinstance(raw_edits, list) and raw_edits:
            for item in raw_edits:
                if isinstance(item, dict):
                    edits.append(
                        FileEdit(
                            turn_index=turn_index,
                            path=path,
                            operation="edit",
                            old_text=_as_str(item.get("old_string")),
                            new_text=_as_str(item.get("new_string")),
                            timestamp=timestamp,
                            call_id=call_id,
                            seq=next_seq(),
                        )
                    )
        elif path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="edit",
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "NotebookEdit":
        path = (
            _as_str(tool_input.get("notebook_path"))
            or _as_str(tool_input.get("file_path"))
            or _as_str(tool_input.get("path"))
        )
        if path:
            edit_mode = _as_str(tool_input.get("edit_mode")) or "replace"
            op: FileOperation
            if edit_mode == "delete":
                op = "delete"
            elif edit_mode == "insert":
                op = "write"
            else:
                op = "edit"
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation=op,
                    old_text=None,
                    new_text=_as_str(tool_input.get("new_source")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    return edits


def parse_claude_code_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse Claude Code JSONL transcript records."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []

    pending_tools: dict[str, ToolExecution] = {}
    failed_call_ids: set[str] = set()
    turn_index = 0
    seq = 0

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    for record in records:
        if detected_session_id is None:
            sid = _as_str(record.get("sessionId")) or _as_str(record.get("session_id"))
            if sid:
                detected_session_id = sid

        if record.get("isSidechain") is True:
            continue

        rec_type = _as_str(record.get("type"))
        timestamp = _as_str(record.get("timestamp"))
        message = record.get("message")
        msg_dict = message if isinstance(message, dict) else {}
        content = msg_dict.get("content")
        tool_use_result = record.get("toolUseResult")
        tur_dict = tool_use_result if isinstance(tool_use_result, dict) else {}

        if rec_type == "user":
            if isinstance(content, list):
                for block in content:
                    if not isinstance(block, dict) or block.get("type") != "tool_result":
                        continue
                    call_id = _as_str(block.get("tool_use_id"))
                    execution = pending_tools.get(call_id) if call_id else None

                    output_text = _extract_text_from_content(block.get("content"))
                    if not output_text and tur_dict:
                        stdout = _as_str(tur_dict.get("stdout")) or ""
                        stderr = _as_str(tur_dict.get("stderr")) or ""
                        output_text = "\n".join(part for part in (stdout, stderr) if part)
                    elif not output_text and isinstance(tool_use_result, str):
                        output_text = sanitize_unicode(tool_use_result)

                    explicit_is_error = (
                        block.get("is_error") if isinstance(block.get("is_error"), bool) else None
                    )
                    is_shell = (
                        execution is not None and execution.tool_name.lower() in _SHELL_TOOL_NAMES
                    )

                    exit_code = (
                        _as_int(block.get("exit_code"))
                        if block.get("exit_code") is not None
                        else _as_int(block.get("exitCode"))
                    )
                    if exit_code is None and tur_dict:
                        for key in ("exit_code", "exitCode", "returnCode", "returncode"):
                            exit_code = _as_int(tur_dict.get(key))
                            if exit_code is not None:
                                break
                    if exit_code is None and is_shell and explicit_is_error is not False:
                        exit_code = _extract_exit_code_from_first_line(output_text)

                    is_error = explicit_is_error is True
                    if exit_code is not None and exit_code != 0:
                        is_error = True

                    if is_error and call_id:
                        failed_call_ids.add(call_id)

                    if execution is not None:
                        execution.output = output_text
                        execution.exit_code = exit_code
                        execution.is_error = is_error
                        if execution.timestamp is None and timestamp is not None:
                            execution.timestamp = timestamp
                    else:
                        tool_executions.append(
                            ToolExecution(
                                turn_index=turn_index,
                                tool_name="unknown",
                                command=None,
                                output=output_text,
                                exit_code=exit_code,
                                is_error=is_error,
                                timestamp=timestamp,
                                call_id=call_id,
                                seq=_next_seq(),
                            )
                        )

            if record.get("isMeta") is True or record.get("isCompactSummary") is True:
                continue

            if isinstance(content, str):
                user_text = _strip_system_reminders(sanitize_unicode(content).strip())
            elif isinstance(content, list):
                text_parts = []
                for block in content:
                    if (
                        isinstance(block, dict)
                        and block.get("type") == "text"
                        and isinstance(block.get("text"), str)
                    ):
                        part = _strip_system_reminders(sanitize_unicode(block["text"]).strip())
                        if part and not _is_claude_noise_user_text(part):
                            text_parts.append(part)
                user_text = "\n".join(text_parts).strip()
            else:
                user_text = ""

            if user_text and not _is_claude_noise_user_text(user_text):
                turn_index += 1
                user_turns.append(
                    UserTurn(
                        turn_index=turn_index,
                        text=user_text,
                        timestamp=timestamp,
                        source="claude-code",
                        seq=_next_seq(),
                    )
                )

        elif rec_type == "assistant" and isinstance(content, list):
            for block in content:
                if not isinstance(block, dict) or block.get("type") != "tool_use":
                    continue
                tool_name = _as_str(block.get("name")) or "unknown"
                call_id = _as_str(block.get("id"))
                raw_input = block.get("input")
                tool_input = raw_input if isinstance(raw_input, dict) else {}

                command: str | None = None
                if tool_name.lower() in _SHELL_TOOL_NAMES:
                    command = _format_command_arg(
                        tool_input.get("command") or tool_input.get("cmd")
                    )

                execution = ToolExecution(
                    turn_index=turn_index,
                    tool_name=tool_name,
                    command=command,
                    output="",
                    exit_code=None,
                    is_error=False,
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=_next_seq(),
                )
                tool_executions.append(execution)
                if call_id:
                    pending_tools[call_id] = execution

                extracted_edits = _extract_claude_file_edits(
                    tool_name,
                    tool_input,
                    turn_index=turn_index,
                    timestamp=timestamp,
                    call_id=call_id,
                    next_seq=_next_seq,
                )
                file_edits.extend(extracted_edits)

    # Drop file edits whose correlated tool_result failed/rejected the edit.
    valid_edits = [
        edit for edit in file_edits if edit.call_id is None or edit.call_id not in failed_call_ids
    ]
    modified_files: list[str] = []
    seen_files: set[str] = set()
    for edit in valid_edits:
        _add_modified_file(modified_files, seen_files, edit.path)

    return ParsedTranscript(
        format="claude-code",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=valid_edits,
        modified_files=modified_files,
    )


def _unwrap_codex_output(raw_output: Any, *, is_shell: bool) -> tuple[str, int | None]:
    """Extract output text and optional exit code from a Codex tool output payload.

    Only inspects Codex header lines (before ``Output:\\n``) for exit codes and only
    unwraps structured Codex JSON envelopes so arbitrary command stdout is never
    misinterpreted as metadata.
    """
    if isinstance(raw_output, dict):
        output_val = raw_output.get("output")
        meta = raw_output.get("metadata")
        is_envelope = isinstance(output_val, str) and (
            isinstance(meta, dict) or set(raw_output.keys()) <= {"output", "metadata", "exit_code"}
        )
        if not is_envelope:
            return sanitize_unicode(json.dumps(raw_output, ensure_ascii=False)), None

        output = sanitize_unicode(output_val)
        exit_code = _as_int(meta.get("exit_code")) if isinstance(meta, dict) else None
        if exit_code is None:
            exit_code = _as_int(raw_output.get("exit_code"))
        if exit_code is None and is_shell:
            exit_code = _extract_exit_code_from_first_line(output)
        return output, exit_code

    if not isinstance(raw_output, str):
        return "", None

    clean_raw = sanitize_unicode(raw_output)
    stripped = clean_raw.strip()
    if stripped.startswith("{") and stripped.endswith("}"):
        try:
            decoded = json.loads(stripped)
        except (json.JSONDecodeError, ValueError, RecursionError):
            decoded = None
        if (
            isinstance(decoded, dict)
            and isinstance(decoded.get("output"), str)
            and (
                isinstance(decoded.get("metadata"), dict)
                or set(decoded.keys()) <= {"output", "metadata", "exit_code"}
            )
        ):
            return _unwrap_codex_output(decoded, is_shell=is_shell)

    if clean_raw.startswith(_CODEX_HEADER_PREFIXES):
        marker = "\nOutput:\n"
        marker_idx = clean_raw.find(marker)
        if marker_idx != -1:
            header_block = clean_raw[:marker_idx]
            body = clean_raw[marker_idx + len(marker) :]
        else:
            header_block = clean_raw
            body = clean_raw

        exit_code: int | None = None
        if is_shell:
            for header_line in header_block.split("\n"):
                match = _HEADER_EXIT_CODE_RE.match(header_line.strip())
                if match:
                    exit_code = int(match.group(1))
                    break
        return body, exit_code

    exit_code = _extract_exit_code_from_first_line(clean_raw) if is_shell else None
    return clean_raw, exit_code


def parse_codex_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse Codex CLI / Responses API JSONL transcript records."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []
    extra_move_paths: list[tuple[str | None, str]] = []

    pending_tools: dict[str, ToolExecution] = {}
    failed_call_ids: set[str] = set()
    turn_index = 0
    seq = 0
    last_user_origin: str | None = None
    activity_since_last_user = True

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    def _record_user_turn(text: str, timestamp: str | None, origin: str) -> None:
        nonlocal turn_index, last_user_origin, activity_since_last_user
        cleaned = sanitize_unicode(text).strip()
        if not cleaned or _is_codex_harness_user_text(cleaned):
            return
        # Codex frequently logs both response_item(message/user) and event_msg(user_message)
        # for the exact same user turn; deduplicate consecutive cross-origin emissions even
        # when one copy has extra attachment/image wrapper text.
        if (
            user_turns
            and not activity_since_last_user
            and last_user_origin is not None
            and last_user_origin != origin
        ):
            prev_text = user_turns[-1].text
            if prev_text == cleaned or cleaned in prev_text or prev_text in cleaned:
                if len(cleaned) > len(prev_text):
                    user_turns[-1].text = cleaned
                return
        turn_index += 1
        user_turns.append(
            UserTurn(
                turn_index=turn_index,
                text=cleaned,
                timestamp=timestamp,
                source="codex",
                seq=_next_seq(),
            )
        )
        last_user_origin = origin
        activity_since_last_user = False

    def _record_patch(patch_text: str, timestamp: str | None, call_id: str | None) -> None:
        patch_edits, move_sources = _parse_apply_patch(
            patch_text,
            turn_index=turn_index,
            timestamp=timestamp,
            call_id=call_id,
            next_seq=_next_seq,
        )
        file_edits.extend(patch_edits)
        for src_path in move_sources:
            extra_move_paths.append((call_id, src_path))

    for record in records:
        rec_type = _as_str(record.get("type"))
        timestamp = _as_str(record.get("timestamp"))
        payload = record.get("payload")
        payload_dict = payload if isinstance(payload, dict) else {}

        if rec_type == "session_meta":
            if detected_session_id is None:
                sid = _as_str(payload_dict.get("id")) or _as_str(record.get("id"))
                if sid:
                    detected_session_id = sid
            continue

        if rec_type == "event_msg":
            event_type = _as_str(payload_dict.get("type"))
            if event_type == "user_message":
                msg_text = _as_str(payload_dict.get("message")) or _as_str(payload_dict.get("text"))
                if msg_text:
                    _record_user_turn(msg_text, timestamp, origin="event_msg")
            elif event_type in ("agent_message", "exec_command_end", "patch_apply_end"):
                activity_since_last_user = True
            continue

        item = payload_dict if rec_type == "response_item" else record
        item_type = _as_str(item.get("type"))

        if item_type == "message":
            role = _as_str(item.get("role"))
            if role == "user":
                text = _extract_text_from_content(item.get("content"))
                _record_user_turn(text, timestamp, origin="response_item")
            elif role == "assistant":
                activity_since_last_user = True

        elif item_type == "function_call":
            activity_since_last_user = True
            tool_name = _as_str(item.get("name")) or "unknown"
            call_id = _as_str(item.get("call_id"))
            raw_args = item.get("arguments")
            args: dict[str, Any] = {}
            if isinstance(raw_args, dict):
                args = raw_args
            elif isinstance(raw_args, str):
                try:
                    decoded_args = json.loads(raw_args)
                    if isinstance(decoded_args, dict):
                        args = decoded_args
                except (json.JSONDecodeError, ValueError, RecursionError):
                    args = {}

            raw_cmd = args.get("command") or args.get("cmd")
            command: str | None = None
            if tool_name.lower() in _SHELL_TOOL_NAMES:
                command = _format_command_arg(raw_cmd)

            execution = ToolExecution(
                turn_index=turn_index,
                tool_name=tool_name,
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            if tool_name == "apply_patch":
                patch_text = (
                    _as_str(args.get("input"))
                    or _as_str(args.get("patch"))
                    or (_as_str(raw_args) if not args else None)
                )
                if patch_text:
                    _record_patch(patch_text, timestamp, call_id)
            elif tool_name.lower() in _SHELL_TOOL_NAMES:
                shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
                if shell_patch:
                    _record_patch(shell_patch, timestamp, call_id)

        elif item_type == "custom_tool_call":
            activity_since_last_user = True
            tool_name = _as_str(item.get("name")) or "unknown"
            call_id = _as_str(item.get("call_id"))
            raw_input = item.get("input")

            command = None
            raw_cmd = None
            if tool_name.lower() in _SHELL_TOOL_NAMES:
                if isinstance(raw_input, dict):
                    raw_cmd = raw_input.get("command") or raw_input.get("cmd")
                    command = _format_command_arg(raw_cmd)
                elif isinstance(raw_input, str):
                    command = sanitize_unicode(raw_input)

            execution = ToolExecution(
                turn_index=turn_index,
                tool_name=tool_name,
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            if tool_name == "apply_patch" and isinstance(raw_input, str):
                _record_patch(raw_input, timestamp, call_id)
            elif tool_name.lower() in _SHELL_TOOL_NAMES:
                shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
                if shell_patch:
                    _record_patch(shell_patch, timestamp, call_id)

        elif item_type == "local_shell_call":
            activity_since_last_user = True
            call_id = _as_str(item.get("call_id"))
            action = item.get("action")
            action_dict = action if isinstance(action, dict) else {}
            raw_cmd = action_dict.get("command") or item.get("command")
            command = _format_command_arg(raw_cmd)
            execution = ToolExecution(
                turn_index=turn_index,
                tool_name="local_shell",
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
            if shell_patch:
                _record_patch(shell_patch, timestamp, call_id)

        elif item_type in (
            "function_call_output",
            "custom_tool_call_output",
            "local_shell_call_output",
        ):
            activity_since_last_user = True
            call_id = _as_str(item.get("call_id"))
            execution = pending_tools.get(call_id) if call_id else None
            is_shell = (
                execution is None
                or execution.tool_name.lower() in _SHELL_TOOL_NAMES
                or execution.tool_name == "apply_patch"
            )
            explicit_is_error = (
                item.get("is_error") if isinstance(item.get("is_error"), bool) else None
            )
            output_text, exit_code = _unwrap_codex_output(
                item.get("output"),
                is_shell=is_shell and explicit_is_error is not False,
            )
            is_error = explicit_is_error is True
            if exit_code is not None and exit_code != 0:
                is_error = True

            if is_error and call_id:
                failed_call_ids.add(call_id)

            if execution is not None:
                execution.output = output_text
                execution.exit_code = exit_code
                execution.is_error = is_error
                if execution.timestamp is None and timestamp is not None:
                    execution.timestamp = timestamp
            else:
                tool_executions.append(
                    ToolExecution(
                        turn_index=turn_index,
                        tool_name="unknown",
                        command=None,
                        output=output_text,
                        exit_code=exit_code,
                        is_error=is_error,
                        timestamp=timestamp,
                        call_id=call_id,
                        seq=_next_seq(),
                    )
                )

    valid_edits = [
        edit for edit in file_edits if edit.call_id is None or edit.call_id not in failed_call_ids
    ]
    modified_files: list[str] = []
    seen_files: set[str] = set()
    move_by_call: dict[str | None, list[str]] = {}
    for cid, src_path in extra_move_paths:
        if cid is None or cid not in failed_call_ids:
            move_by_call.setdefault(cid, []).append(src_path)
    for edit in valid_edits:
        for src_path in move_by_call.pop(edit.call_id, []):
            _add_modified_file(modified_files, seen_files, src_path)
        _add_modified_file(modified_files, seen_files, edit.path)
    for remaining in move_by_call.values():
        for src_path in remaining:
            _add_modified_file(modified_files, seen_files, src_path)

    return ParsedTranscript(
        format="codex",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=valid_edits,
        modified_files=modified_files,
    )


def parse_generic_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse generic flat JSONL transcripts."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []
    modified_files: list[str] = []
    seen_files: set[str] = set()

    turn_index = 0
    seq = 0

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    for record in records:
        if detected_session_id is None:
            sid = _as_str(record.get("session_id")) or _as_str(record.get("sessionId"))
            if sid:
                detected_session_id = sid

        timestamp = _as_str(record.get("timestamp"))
        rec_type = _as_str(record.get("type"))
        role = _as_str(record.get("role"))

        if rec_type == "file_edit":
            path = _as_str(record.get("path")) or _as_str(record.get("file_path"))
            if not path:
                continue
            raw_op = _as_str(record.get("operation")) or "edit"
            op: FileOperation = raw_op if raw_op in VALID_FILE_OPERATIONS else "edit"  # type: ignore[assignment]
            edit = FileEdit(
                turn_index=turn_index,
                path=path,
                operation=op,
                old_text=_as_str(record.get("old_text")) or _as_str(record.get("old_string")),
                new_text=_as_str(record.get("new_text")) or _as_str(record.get("new_string")),
                timestamp=timestamp,
                call_id=_as_str(record.get("call_id")),
                seq=_next_seq(),
            )
            file_edits.append(edit)
            _add_modified_file(modified_files, seen_files, path)
            continue

        if role == "user" or (rec_type == "user" and role is None):
            raw_content = record.get("content")
            if raw_content is None:
                raw_content = record.get("text")
            text = _extract_text_from_content(raw_content).strip()
            if text:
                turn_index += 1
                user_turns.append(
                    UserTurn(
                        turn_index=turn_index,
                        text=text,
                        timestamp=timestamp,
                        source="generic",
                        seq=_next_seq(),
                    )
                )
            continue

        is_tool_record = (
            role == "tool"
            or rec_type in ("tool", "tool_execution", "command", "bash", "shell")
            or "command" in record
        )
        if is_tool_record:
            tool_name = (
                _as_str(record.get("tool_name"))
                or _as_str(record.get("name"))
                or (rec_type if rec_type in ("bash", "shell") else "shell")
            )
            command = _format_command_arg(record.get("command") or record.get("cmd"))
            output_val = record.get("output")
            if output_val is not None:
                output_text = _extract_text_from_content(output_val)
            else:
                stdout = _as_str(record.get("stdout")) or ""
                stderr = _as_str(record.get("stderr")) or ""
                if stdout or stderr:
                    output_text = "\n".join(part for part in (stdout, stderr) if part)
                else:
                    output_text = _extract_text_from_content(record.get("content"))

            explicit_is_error = (
                record.get("is_error") if isinstance(record.get("is_error"), bool) else None
            )
            exit_code = _as_int(record.get("exit_code"))
            if exit_code is None:
                exit_code = _as_int(record.get("exitCode"))
            is_shell = tool_name.lower() in _SHELL_TOOL_NAMES or command is not None
            if exit_code is None and is_shell and explicit_is_error is not False:
                exit_code = _extract_exit_code_from_first_line(output_text)

            is_error = explicit_is_error is True
            if exit_code is not None and exit_code != 0:
                is_error = True

            tool_executions.append(
                ToolExecution(
                    turn_index=turn_index,
                    tool_name=tool_name,
                    command=command,
                    output=output_text,
                    exit_code=exit_code,
                    is_error=is_error,
                    timestamp=timestamp,
                    call_id=_as_str(record.get("call_id")) or _as_str(record.get("id")),
                    seq=_next_seq(),
                )
            )

    return ParsedTranscript(
        format="generic",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=file_edits,
        modified_files=modified_files,
    )


def parse_transcript_lines(
    lines: Iterable[str],
    *,
    fmt: str = "auto",
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse transcript JSONL lines using auto-detection or an explicit format."""
    if fmt not in SUPPORTED_FORMATS:
        raise ValueError(
            f"Unsupported transcript format {fmt!r}; expected one of {sorted(SUPPORTED_FORMATS)}"
        )

    records = _iter_json_records(lines)
    if not records:
        return ParsedTranscript(
            format="unknown" if fmt == "auto" else fmt,
            session_id=session_id,
        )

    resolved_fmt = detect_transcript_format(records) if fmt == "auto" else fmt
    if resolved_fmt == "claude-code":
        return parse_claude_code_records(records, session_id=session_id)
    if resolved_fmt == "codex":
        return parse_codex_records(records, session_id=session_id)
    return parse_generic_records(records, session_id=session_id)


def parse_transcript(
    path: str | Path,
    *,
    fmt: str = "auto",
    session_id: str | None = None,
) -> ParsedTranscript:
    """Read and parse a JSONL transcript file from disk."""
    transcript_path = Path(path)
    with transcript_path.open("r", encoding="utf-8", errors="replace") as handle:
        return parse_transcript_lines(handle, fmt=fmt, session_id=session_id)
