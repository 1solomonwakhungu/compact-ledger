def _paths_overlap(a_paths: frozenset[str], b_paths: frozenset[str]) -> bool:
    """Return True if two path sets share an exact or relative/absolute suffix match."""
    if not a_paths or not b_paths:
        return False
    if a_paths & b_paths:
        return True
    norm_a = [p.replace("\\", "/").lstrip("./") for p in a_paths]
    norm_b = [p.replace("\\", "/").lstrip("./") for p in b_paths]
    for a in norm_a:
        for b in norm_b:
            if a == b or a.endswith("/" + b) or b.endswith("/" + a):
                return True
    return False


def _extract_patch_paths(patch_text: str) -> frozenset[str]:
    """Quickly collect file paths referenced by an ``apply_patch`` payload."""
    paths: set[str] = set()
    for line in sanitize_unicode(patch_text).replace("\r\n", "\n").split("\n"):
        for prefix in ("*** Update File:", "*** Add File:", "*** Delete File:", "*** Move to:"):
            if line.startswith(prefix):
                val = line.split(":", 1)[1].strip()
                if val:
                    paths.add(val)
                break
    return frozenset(paths)


def _iter_json_records(lines: Iterable[str]) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    first = True
    for raw_line in lines:
        if first:
            first = False
            if raw_line.startswith("\ufeff"):
                raw_line = raw_line[1:]
        stripped = raw_line.strip()
        if not stripped:
            continue
        try:
            parsed = json.loads(stripped)
        except (json.JSONDecodeError, ValueError, RecursionError):
            continue
        if isinstance(parsed, dict):
            records.append(parsed)
    return records


def detect_transcript_format(records: Sequence[dict[str, Any]]) -> str:
    """Detect whether parsed JSONL records are Claude Code, Codex, or generic."""
    if not records:
        return "unknown"

    codex_score = 0
    claude_score = 0
    generic_score = 0

    for record in records[:100]:
        rec_type = record.get("type")
        if isinstance(rec_type, str) and rec_type in _CODEX_WRAPPER_TYPES:
            codex_score += 3
            continue

        if (
            isinstance(rec_type, str)
            and rec_type in _CLAUDE_ENTRY_TYPES
            and (
                isinstance(record.get("message"), dict)
                or "sessionId" in record
                or "parentUuid" in record
                or "toolUseResult" in record
                or rec_type in ("summary", "file-history-snapshot")
            )
        ):
            claude_score += 3
            continue

        if isinstance(record.get("message"), dict):
            content = record["message"].get("content")
            if isinstance(content, list) and any(
                isinstance(b, dict) and b.get("type") in ("tool_use", "tool_result")
                for b in content
            ):
                claude_score += 3
                continue

        if (
            "role" in record
            or "command" in record
            or rec_type in ("file_edit", "tool", "tool_execution", "command")
        ):
            generic_score += 1

    if codex_score > 0 and codex_score >= claude_score:
        return "codex"
    if claude_score > 0:
        return "claude-code"
    if generic_score > 0:
        return "generic"
    return "generic"


def _strip_system_reminders(text: str) -> str:
    """Remove ``<system-reminder>...</system-reminder>`` spans in O(N).

    Claude Code appends reminders to genuine user messages; an unclosed tag drops the rest.
    """
    if _SYSTEM_REMINDER_OPEN not in text:
        return text
    parts: list[str] = []
    pos = 0
    while True:
        start = text.find(_SYSTEM_REMINDER_OPEN, pos)
        if start == -1:
            parts.append(text[pos:])
            break
        parts.append(text[pos:start])
        end = text.find(_SYSTEM_REMINDER_CLOSE, start)
        if end == -1:
            break
        pos = end + len(_SYSTEM_REMINDER_CLOSE)
    return "".join(parts).strip()


def _is_claude_noise_user_text(text: str) -> bool:
    if text.startswith(_CLAUDE_NOISE_PREFIXES):
        return True
    if _CLAUDE_HOOK_FEEDBACK_RE.match(text):
        return True
    return bool(_CLAUDE_WRAPPER_TAG_RE.match(text))


def _is_codex_harness_user_text(text: str) -> bool:
    return text.startswith(_CODEX_HARNESS_PREFIXES)


def _extract_claude_file_edits(
    tool_name: str,
    tool_input: dict[str, Any],
    *,
    turn_index: int,
    timestamp: str | None,
    call_id: str | None,
    next_seq: Any,
) -> list[FileEdit]:
    edits: list[FileEdit] = []
    if tool_name == "Edit":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        if path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="edit",
                    old_text=_as_str(tool_input.get("old_string")),
                    new_text=_as_str(tool_input.get("new_string")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "Write":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        if path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="write",
                    old_text=None,
                    new_text=_as_str(tool_input.get("content")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "MultiEdit":
        path = _as_str(tool_input.get("file_path")) or _as_str(tool_input.get("path"))
        raw_edits = tool_input.get("edits")
        if path and isinstance(raw_edits, list) and raw_edits:
            for item in raw_edits:
                if isinstance(item, dict):
                    edits.append(
                        FileEdit(
                            turn_index=turn_index,
                            path=path,
                            operation="edit",
                            old_text=_as_str(item.get("old_string")),
                            new_text=_as_str(item.get("new_string")),
                            timestamp=timestamp,
                            call_id=call_id,
                            seq=next_seq(),
                        )
                    )
        elif path:
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation="edit",
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    elif tool_name == "NotebookEdit":
        path = (
            _as_str(tool_input.get("notebook_path"))
            or _as_str(tool_input.get("file_path"))
            or _as_str(tool_input.get("path"))
        )
        if path:
            edit_mode = _as_str(tool_input.get("edit_mode")) or "replace"
            op: FileOperation
            if edit_mode == "delete":
                op = "delete"
            elif edit_mode == "insert":
                op = "write"
            else:
                op = "edit"
            edits.append(
                FileEdit(
                    turn_index=turn_index,
                    path=path,
                    operation=op,
                    old_text=None,
                    new_text=_as_str(tool_input.get("new_source")),
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=next_seq(),
                )
            )
    return edits


def parse_claude_code_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse Claude Code JSONL transcript records."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []

    pending_tools: dict[str, ToolExecution] = {}
    failed_call_ids: set[str] = set()
    turn_index = 0
    seq = 0

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    for record in records:
        if detected_session_id is None:
            sid = _as_str(record.get("sessionId")) or _as_str(record.get("session_id"))
            if sid:
                detected_session_id = sid

        if record.get("isSidechain") is True:
            continue

        rec_type = _as_str(record.get("type"))
        timestamp = _as_str(record.get("timestamp"))
        message = record.get("message")
        msg_dict = message if isinstance(message, dict) else {}
        content = msg_dict.get("content")
        tool_use_result = record.get("toolUseResult")
        tur_dict = tool_use_result if isinstance(tool_use_result, dict) else {}

        if rec_type == "user":
            if isinstance(content, list):
                for block in content:
                    if not isinstance(block, dict) or block.get("type") != "tool_result":
                        continue
                    call_id = _as_str(block.get("tool_use_id"))
                    execution = pending_tools.get(call_id) if call_id else None

                    output_text = _extract_text_from_content(block.get("content"))
                    if not output_text and tur_dict:
                        stdout = _as_str(tur_dict.get("stdout")) or ""
                        stderr = _as_str(tur_dict.get("stderr")) or ""
                        output_text = "\n".join(part for part in (stdout, stderr) if part)
                    elif not output_text and isinstance(tool_use_result, str):
                        output_text = sanitize_unicode(tool_use_result)

                    explicit_is_error = (
                        block.get("is_error") if isinstance(block.get("is_error"), bool) else None
                    )
                    is_shell = (
                        execution is not None and execution.tool_name.lower() in _SHELL_TOOL_NAMES
                    )

                    exit_code = (
                        _as_int(block.get("exit_code"))
                        if block.get("exit_code") is not None
                        else _as_int(block.get("exitCode"))
                    )
                    if exit_code is None and tur_dict:
                        for key in ("exit_code", "exitCode", "returnCode", "returncode"):
                            exit_code = _as_int(tur_dict.get(key))
                            if exit_code is not None:
                                break
                    if exit_code is None and is_shell and explicit_is_error is not False:
                        exit_code = _extract_exit_code_from_first_line(output_text)

                    is_error = explicit_is_error is True
                    if exit_code is not None and exit_code != 0:
                        is_error = True

                    if is_error and call_id:
                        failed_call_ids.add(call_id)

                    if execution is not None:
                        execution.output = output_text
                        execution.exit_code = exit_code
                        execution.is_error = is_error
                        if execution.timestamp is None and timestamp is not None:
                            execution.timestamp = timestamp
                    else:
                        tool_executions.append(
                            ToolExecution(
                                turn_index=turn_index,
                                tool_name="unknown",
                                command=None,
                                output=output_text,
                                exit_code=exit_code,
                                is_error=is_error,
                                timestamp=timestamp,
                                call_id=call_id,
                                seq=_next_seq(),
                            )
                        )

            if record.get("isMeta") is True or record.get("isCompactSummary") is True:
                continue

            if isinstance(content, str):
                user_text = _strip_system_reminders(sanitize_unicode(content).strip())
            elif isinstance(content, list):
                text_parts = []
                for block in content:
                    if (
                        isinstance(block, dict)
                        and block.get("type") == "text"
                        and isinstance(block.get("text"), str)
                    ):
                        part = _strip_system_reminders(sanitize_unicode(block["text"]).strip())
                        if part and not _is_claude_noise_user_text(part):
                            text_parts.append(part)
                user_text = "\n".join(text_parts).strip()
            else:
                user_text = ""

            if user_text and not _is_claude_noise_user_text(user_text):
                turn_index += 1
                user_turns.append(
                    UserTurn(
                        turn_index=turn_index,
                        text=user_text,
                        timestamp=timestamp,
                        source="claude-code",
                        seq=_next_seq(),
                    )
                )

        elif rec_type == "assistant" and isinstance(content, list):
            for block in content:
                if not isinstance(block, dict) or block.get("type") != "tool_use":
                    continue
                tool_name = _as_str(block.get("name")) or "unknown"
                call_id = _as_str(block.get("id"))
                raw_input = block.get("input")
                tool_input = raw_input if isinstance(raw_input, dict) else {}

                command: str | None = None
                if tool_name.lower() in _SHELL_TOOL_NAMES:
                    command = _format_command_arg(
                        tool_input.get("command") or tool_input.get("cmd")
                    )

                execution = ToolExecution(
                    turn_index=turn_index,
                    tool_name=tool_name,
                    command=command,
                    output="",
                    exit_code=None,
                    is_error=False,
                    timestamp=timestamp,
                    call_id=call_id,
                    seq=_next_seq(),
                )
                tool_executions.append(execution)
                if call_id:
                    pending_tools[call_id] = execution

                extracted_edits = _extract_claude_file_edits(
                    tool_name,
                    tool_input,
                    turn_index=turn_index,
                    timestamp=timestamp,
                    call_id=call_id,
                    next_seq=_next_seq,
                )
                file_edits.extend(extracted_edits)

    # Drop file edits whose correlated tool_result failed/rejected the edit.
    valid_edits = [
        edit for edit in file_edits if edit.call_id is None or edit.call_id not in failed_call_ids
    ]
    modified_files: list[str] = []
    seen_files: set[str] = set()
    for edit in valid_edits:
        _add_modified_file(modified_files, seen_files, edit.path)

    return ParsedTranscript(
        format="claude-code",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=valid_edits,
        modified_files=modified_files,
    )


def _unwrap_codex_output(raw_output: Any, *, is_shell: bool) -> tuple[str, int | None]:
    """Extract output text and optional exit code from a Codex tool output payload.

    Only inspects Codex header lines (before ``Output:\\n``) for exit codes and only
    unwraps structured Codex JSON envelopes so arbitrary command stdout is never
    misinterpreted as metadata.
    """
    if isinstance(raw_output, list):
        joined = _join_codex_content_blocks(raw_output)
        return _unwrap_codex_output(joined, is_shell=is_shell)

    if isinstance(raw_output, dict):
        output_val = raw_output.get("output")
        meta = raw_output.get("metadata")
        is_envelope = isinstance(output_val, str) and (
            isinstance(meta, dict) or set(raw_output.keys()) <= _CODEX_EXEC_ENVELOPE_KEYS
        )
        if not is_envelope:
            if "exit_code" in raw_output and _as_int(raw_output.get("exit_code")) is not None:
                stdout = _as_str(raw_output.get("stdout")) or ""
                stderr = _as_str(raw_output.get("stderr")) or ""
                combined = "\n".join(part for part in (stdout, stderr) if part)
                return combined, _as_int(raw_output.get("exit_code"))
            return sanitize_unicode(json.dumps(raw_output, ensure_ascii=False)), None

        output = sanitize_unicode(output_val)
        exit_code = _as_int(meta.get("exit_code")) if isinstance(meta, dict) else None
        if exit_code is None:
            exit_code = _as_int(raw_output.get("exit_code"))
        if exit_code is None and is_shell:
            exit_code = _extract_exit_code_from_first_line(output)
        return output, exit_code

    if not isinstance(raw_output, str):
        return "", None

    clean_raw = sanitize_unicode(raw_output)
    stripped = clean_raw.strip()
    if stripped.startswith("{") and stripped.endswith("}"):
        try:
            decoded = json.loads(stripped)
        except (json.JSONDecodeError, ValueError, RecursionError):
            decoded = None
        if (
            isinstance(decoded, dict)
            and isinstance(decoded.get("output"), str)
            and (
                isinstance(decoded.get("metadata"), dict)
                or set(decoded.keys()) <= _CODEX_EXEC_ENVELOPE_KEYS
            )
        ):
            return _unwrap_codex_output(decoded, is_shell=is_shell)

    if clean_raw.startswith(_CODEX_HEADER_PREFIXES):
        marker = "\nOutput:\n"
        marker_idx = clean_raw.find(marker)
        if marker_idx != -1:
            header_block = clean_raw[:marker_idx]
            body = clean_raw[marker_idx + len(marker) :]
        else:
            header_block = clean_raw
            body = clean_raw

        exit_code: int | None = None
        if is_shell:
            for header_line in header_block.split("\n"):
                match = _HEADER_EXIT_CODE_RE.match(header_line.strip())
                if match:
                    exit_code = int(match.group(1))
                    break
        if body != clean_raw:
            body_stripped = body.strip()
            if body_stripped.startswith("{") and body_stripped.endswith("}"):
                inner_out, inner_ec = _unwrap_codex_output(body_stripped, is_shell=is_shell)
                if inner_ec is not None or inner_out != body_stripped:
                    return inner_out, exit_code if exit_code is not None else inner_ec
        return body, exit_code

    exit_code = _extract_exit_code_from_first_line(clean_raw) if is_shell else None
    return clean_raw, exit_code


def parse_codex_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse Codex CLI / Responses API JSONL transcript records."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []
    extra_move_paths: list[tuple[str | None, str | None, str]] = []

    pending_tools: dict[str, ToolExecution] = {}
    pending_execs: dict[str, _PendingCodexExec] = {}
    open_exec_order: list[str] = []
    fallback_cmd_execs: list[ToolExecution] = []
    fallback_patch_records: list[_FallbackPatchRecord] = []
    failed_call_ids: set[str] = set()
    turn_index = 0
    seq = 0
    last_user_origins: set[str] = set()
    activity_since_last_user = True

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    def _live_pending_execs() -> list[_PendingCodexExec]:
        live: list[_PendingCodexExec] = []
        cleaned_order: list[str] = []
        for cid in open_exec_order:
            pending = pending_execs.get(cid)
            if pending is not None:
                cleaned_order.append(cid)
                live.append(pending)
        open_exec_order[:] = cleaned_order
        return live

    def _claim_open_exec_cmd(cmd: str | None) -> bool:
        if not cmd:
            return False
        for pending in _live_pending_execs():
            for idx, exp_cmd in enumerate(pending.expected_cmds):
                if idx not in pending.matched_cmd_indices and exp_cmd == cmd:
                    pending.matched_cmd_indices.add(idx)
                    return True
        return False

    def _claim_open_exec_patch(paths: frozenset[str]) -> bool:
        live = _live_pending_execs()
        if paths:
            for pending in live:
                for idx, exp_paths in enumerate(pending.expected_patch_paths):
                    if idx not in pending.matched_patch_indices and _paths_overlap(
                        exp_paths, paths
                    ):
                        pending.matched_patch_indices.add(idx)
                        return True
        for pending in live:
            for idx in range(len(pending.expected_patches)):
                if idx not in pending.matched_patch_indices:
                    pending.matched_patch_indices.add(idx)
                    return True
        return False

    def _enqueue_fallback_cmd(exe: ToolExecution) -> None:
        # Drop any stale queued fallbacks for the same command from earlier exec calls so a
        # late event from a newer run can never overwrite an older run's record.
        if exe.command:
            fallback_cmd_execs[:] = [
                prev for prev in fallback_cmd_execs if prev.command != exe.command
            ]
        fallback_cmd_execs.append(exe)

    def _reconcile_fallback_cmd(
        cmd: str | None,
        *,
        output: str,
        exit_code: int | None,
        is_error: bool,
        timestamp: str | None,
        call_id: str | None,
    ) -> bool:
        if not cmd:
            return False
        for idx in range(len(fallback_cmd_execs) - 1, -1, -1):
            fb_exec = fallback_cmd_execs[idx]
            if fb_exec.command == cmd:
                fb_exec.output = output
                fb_exec.exit_code = exit_code
                fb_exec.is_error = is_error
                if call_id:
                    fb_exec.call_id = call_id
                if timestamp:
                    fb_exec.timestamp = timestamp
                fallback_cmd_execs.pop(idx)
                return True
        return False

    def _remove_fallback_patch(paths: frozenset[str]) -> bool:
        if not paths:
            return False
        for idx in range(len(fallback_patch_records) - 1, -1, -1):
            fb = fallback_patch_records[idx]
            if _paths_overlap(fb.paths, paths):
                drop_ids = {id(e) for e in fb.edits}
                file_edits[:] = [e for e in file_edits if id(e) not in drop_ids]
                if fb.moves:
                    drop_moves = set(fb.moves)
                    extra_move_paths[:] = [m for m in extra_move_paths if m not in drop_moves]
                fallback_patch_records.pop(idx)
                return True
        return False

    def _finalize_exec_call(
        pending: _PendingCodexExec,
        raw_output: Any,
        *,
        explicit_is_error: bool | None,
        out_timestamp: str | None,
        is_eof_leftover: bool = False,
    ) -> None:
        raw_joined = (
            _join_codex_content_blocks(raw_output)
            if isinstance(raw_output, list)
            else (_as_str(raw_output) or "")
        )
        script_failed = explicit_is_error is True or raw_joined.startswith("Script failed")
        unwrapped_body, header_exit = _unwrap_codex_output(
            raw_output,
            is_shell=explicit_is_error is not False,
        )
        ts = pending.timestamp or out_timestamp

        unmatched_patches = [
            patch_text
            for idx, patch_text in enumerate(pending.expected_patches)
            if idx not in pending.matched_patch_indices
        ]
        if unmatched_patches and not script_failed and not is_eof_leftover:
            lower_body = unwrapped_body.lower()
            patch_failed = any(marker in lower_body for marker in _CODEX_PATCH_FAIL_MARKERS)
            if not patch_failed:
                for patch_text in unmatched_patches:
                    new_edits, new_moves = _record_patch(
                        patch_text,
                        ts,
                        pending.call_id,
                        edit_turn_index=pending.turn_index,
                    )
                    if new_edits:
                        fallback_patch_records.append(
                            _FallbackPatchRecord(
                                paths=frozenset(
                                    [e.path for e in new_edits] + [m[2] for m in new_moves]
                                ),
                                edits=new_edits,
                                moves=new_moves,
                            )
                        )

        unmatched_cmd_pairs = [
            (idx, cmd)
            for idx, cmd in enumerate(pending.expected_cmds)
            if idx not in pending.matched_cmd_indices
        ]
        if unmatched_cmd_pairs:
            structured = _extract_codex_exec_results(unwrapped_body)
            if structured is not None:
                # Align structured results against ALL expected commands (tail-aligned when
                # fewer results were printed than calls) so partial in-window claims keep exact
                # index alignment.
                total_expected = len(pending.expected_cmds)
                offset = max(0, total_expected - len(structured))
                first_emitted = True
                for orig_idx, formatted_cmd in unmatched_cmd_pairs:
                    res_idx = orig_idx - offset
                    if 0 <= res_idx < len(structured):
                        out_text, ec = structured[res_idx]
                    else:
                        out_text, ec = "", None
                    is_err = (ec is not None and ec != 0) or (
                        script_failed and ec is None and orig_idx == total_expected - 1
                    )
                    exe = ToolExecution(
                        turn_index=pending.turn_index,
                        tool_name="exec_command",
                        command=formatted_cmd,
                        output=out_text,
                        exit_code=ec,
                        is_error=is_err,
                        timestamp=ts,
                        call_id=(
                            pending.call_id
                            if len(unmatched_cmd_pairs) == 1
                            else (f"{pending.call_id}#{orig_idx}" if pending.call_id else None)
                        ),
                        seq=pending.seq if first_emitted else _next_seq(),
                    )
                    first_emitted = False
                    tool_executions.append(exe)
                    _enqueue_fallback_cmd(exe)
            elif not is_eof_leftover:
                for pos, (orig_idx, formatted_cmd) in enumerate(unmatched_cmd_pairs):
                    is_last = pos == len(unmatched_cmd_pairs) - 1
                    out_text = unwrapped_body if is_last else ""
                    ec = header_exit if is_last else None
                    is_err = is_last and (script_failed or (ec is not None and ec != 0))
                    exe = ToolExecution(
                        turn_index=pending.turn_index,
                        tool_name="exec_command",
                        command=formatted_cmd,
                        output=out_text,
                        exit_code=ec,
                        is_error=is_err,
                        timestamp=ts,
                        call_id=(
                            pending.call_id
                            if len(unmatched_cmd_pairs) == 1
                            else (f"{pending.call_id}#{orig_idx}" if pending.call_id else None)
                        ),
                        seq=pending.seq if pos == 0 else _next_seq(),
                    )
                    tool_executions.append(exe)
                    _enqueue_fallback_cmd(exe)
        elif (
            not pending.expected_cmds
            and not pending.expected_patches
            and not pending.matched_cmd_indices
            and not pending.matched_patch_indices
            and not is_eof_leftover
        ):
            tool_executions.append(
                ToolExecution(
                    turn_index=pending.turn_index,
                    tool_name="exec",
                    command=None,
                    output=unwrapped_body,
                    exit_code=header_exit,
                    is_error=script_failed or (header_exit is not None and header_exit != 0),
                    timestamp=ts,
                    call_id=pending.call_id,
                    seq=pending.seq,
                )
            )

    def _record_file_change_event(item: dict[str, Any], timestamp: str | None) -> None:
        status = (_as_str(item.get("status")) or "completed").lower()
        call_id = _as_str(item.get("id"))
        raw_changes = item.get("changes")
        entries: list[tuple[str, dict[str, Any]]] = []
        if isinstance(raw_changes, dict):
            for raw_path, change in raw_changes.items():
                path_str = _as_str(raw_path)
                if path_str and isinstance(change, dict):
                    entries.append((path_str.strip(), change))
        elif isinstance(raw_changes, list):
            for change in raw_changes:
                if not isinstance(change, dict):
                    continue
                path_str = _as_str(change.get("path")) or _as_str(change.get("file_path"))
                if path_str:
                    entries.append((path_str.strip(), change))

        event_paths: set[str] = set()
        for path_str, change in entries:
            if path_str:
                event_paths.add(path_str)
                mp = _as_str(change.get("move_path"))
                if mp and mp.strip():
                    event_paths.add(mp.strip())
        frozen_paths = frozenset(event_paths)

        if not _claim_open_exec_patch(frozen_paths):
            _remove_fallback_patch(frozen_paths)

        if status in _CODEX_FAILED_STATUSES or status in _CODEX_SKIPPED_STATUSES:
            return

        for path_str, change in entries:
            if not path_str:
                continue
            ctype = (_as_str(change.get("type")) or _as_str(change.get("kind")) or "update").lower()
            if ctype in ("add", "create", "write"):
                file_edits.append(
                    FileEdit(
                        turn_index=turn_index,
                        path=path_str,
                        operation="write",
                        old_text=None,
                        new_text=_as_str(change.get("content")),
                        timestamp=timestamp,
                        call_id=call_id,
                        seq=_next_seq(),
                    )
                )
            elif ctype in ("delete", "remove"):
                file_edits.append(
                    FileEdit(
                        turn_index=turn_index,
                        path=path_str,
                        operation="delete",
                        old_text=_as_str(change.get("content")),
                        new_text=None,
                        timestamp=timestamp,
                        call_id=call_id,
                        seq=_next_seq(),
                    )
                )
            else:
                move_path = _as_str(change.get("move_path"))
                target_path = move_path.strip() if move_path and move_path.strip() else path_str
                if target_path != path_str:
                    extra_move_paths.append((call_id, target_path, path_str))
                udiff = _as_str(change.get("unified_diff")) or _as_str(change.get("diff")) or ""
                file_edits.extend(
                    _parse_unified_diff_hunks(
                        udiff,
                        path=target_path,
                        turn_index=turn_index,
                        timestamp=timestamp,
                        call_id=call_id,
                        next_seq=_next_seq,
                    )
                )

    def _record_user_turn(text: str, timestamp: str | None, origin: str) -> None:
        nonlocal turn_index, activity_since_last_user
        cleaned = sanitize_unicode(text).strip()
        if not cleaned or _is_codex_harness_user_text(cleaned):
            return
        # Codex frequently logs multiple records (response_item/message, event_msg/user_message,
        # event_msg/item_completed/UserMessage) for the exact same user turn; deduplicate
        # consecutive cross-origin emissions without merging distinct short replies like "ok".
        if user_turns and not activity_since_last_user and origin not in last_user_origins:
            prev_text = user_turns[-1].text
            shorter, longer = (
                (prev_text, cleaned) if len(prev_text) <= len(cleaned) else (cleaned, prev_text)
            )
            is_same_turn = prev_text == cleaned or (
                shorter in longer
                and (
                    longer.startswith(shorter)
                    or longer.endswith(shorter)
                    or (len(shorter) >= 20 and len(shorter) * 2 >= len(longer))
                )
            )
            if is_same_turn:
                if len(cleaned) > len(prev_text):
                    user_turns[-1].text = cleaned
                last_user_origins.add(origin)
                return
        turn_index += 1
        user_turns.append(
            UserTurn(
                turn_index=turn_index,
                text=cleaned,
                timestamp=timestamp,
                source="codex",
                seq=_next_seq(),
            )
        )
        last_user_origins.clear()
        last_user_origins.add(origin)
        activity_since_last_user = False

    def _record_patch(
        patch_text: str,
        timestamp: str | None,
        call_id: str | None,
        *,
        edit_turn_index: int | None = None,
    ) -> tuple[list[FileEdit], list[tuple[str | None, str | None, str]]]:
        patch_edits, move_pairs = _parse_apply_patch(
            patch_text,
            turn_index=turn_index if edit_turn_index is None else edit_turn_index,
            timestamp=timestamp,
            call_id=call_id,
            next_seq=_next_seq,
        )
        file_edits.extend(patch_edits)
        added_moves: list[tuple[str | None, str | None, str]] = []
        for target_path, src_path in move_pairs:
            entry = (call_id, target_path, src_path)
            extra_move_paths.append(entry)
            added_moves.append(entry)
        return patch_edits, added_moves

    for record in records:
        rec_type = _as_str(record.get("type"))
        timestamp = _as_str(record.get("timestamp"))
        payload = record.get("payload")
        payload_dict = payload if isinstance(payload, dict) else {}

        if rec_type == "session_meta":
            if detected_session_id is None:
                sid = _as_str(payload_dict.get("id")) or _as_str(record.get("id"))
                if sid:
                    detected_session_id = sid
            continue

        if rec_type == "event_msg":
            event_type = _as_str(payload_dict.get("type"))
            if event_type == "user_message":
                msg_text = _as_str(payload_dict.get("message")) or _as_str(payload_dict.get("text"))
                if msg_text:
                    _record_user_turn(msg_text, timestamp, origin="event_msg")
            elif event_type == "item_completed":
                completed = payload_dict.get("item")
                if isinstance(completed, dict):
                    completed_type = _as_str(completed.get("type"))
                    if completed_type == "UserMessage":
                        msg_text = _extract_text_from_content(completed.get("content"))
                        if msg_text:
                            _record_user_turn(msg_text, timestamp, origin="item_completed")
                    elif completed_type == "CommandExecution":
                        activity_since_last_user = True
                        status = (_as_str(completed.get("status")) or "").lower()
                        raw_cmd = completed.get("command") or completed.get("cmd")
                        cmd = _format_command_arg(raw_cmd)
                        out_text = _as_str(completed.get("aggregated_output"))
                        if out_text is None:
                            out_text = _as_str(completed.get("output"))
                        if out_text is None:
                            stdout = _as_str(completed.get("stdout")) or ""
                            stderr = _as_str(completed.get("stderr")) or ""
                            out_text = "\n".join(part for part in (stdout, stderr) if part)
                        exit_code = _as_int(completed.get("exit_code"))
                        claimed_open = _claim_open_exec_cmd(cmd)
                        if not (
                            status in _CODEX_SKIPPED_STATUSES and exit_code is None and not out_text
                        ):
                            is_error = status in _CODEX_FAILED_STATUSES or (
                                exit_code is not None and exit_code != 0
                            )
                            ev_call_id = _as_str(completed.get("id"))
                            reconciled = (
                                False
                                if claimed_open
                                else _reconcile_fallback_cmd(
                                    cmd,
                                    output=out_text or "",
                                    exit_code=exit_code,
                                    is_error=is_error,
                                    timestamp=timestamp,
                                    call_id=ev_call_id,
                                )
                            )
                            if not reconciled:
                                tool_executions.append(
                                    ToolExecution(
                                        turn_index=turn_index,
                                        tool_name="exec_command",
                                        command=cmd,
                                        output=out_text or "",
                                        exit_code=exit_code,
                                        is_error=is_error,
                                        timestamp=timestamp,
                                        call_id=ev_call_id,
                                        seq=_next_seq(),
                                    )
                                )
                            if not is_error:
                                shell_patch = _extract_patch_from_shell_command(raw_cmd, cmd)
                                if shell_patch:
                                    _record_patch(shell_patch, timestamp, ev_call_id)
                    elif completed_type == "FileChange":
                        activity_since_last_user = True
                        _record_file_change_event(completed, timestamp)
                    elif completed_type in ("AgentMessage", "McpToolCall", "CollabAgentToolCall"):
                        activity_since_last_user = True
            elif event_type in ("agent_message", "exec_command_end", "patch_apply_end"):
                activity_since_last_user = True
            continue

        item = payload_dict if rec_type == "response_item" else record
        item_type = _as_str(item.get("type"))

        if item_type == "message":
            role = _as_str(item.get("role"))
            if role == "user":
                text = _extract_text_from_content(item.get("content"))
                _record_user_turn(text, timestamp, origin="response_item")
            elif role == "assistant":
                activity_since_last_user = True

        elif item_type == "function_call":
            activity_since_last_user = True
            tool_name = _as_str(item.get("name")) or "unknown"
            call_id = _as_str(item.get("call_id"))
            raw_args = item.get("arguments")
            args: dict[str, Any] = {}
            if isinstance(raw_args, dict):
                args = raw_args
            elif isinstance(raw_args, str):
                try:
                    decoded_args = json.loads(raw_args)
                    if isinstance(decoded_args, dict):
                        args = decoded_args
                except (json.JSONDecodeError, ValueError, RecursionError):
                    args = {}

            raw_cmd = args.get("command") or args.get("cmd")
            command: str | None = None
            if tool_name.lower() in _SHELL_TOOL_NAMES:
                command = _format_command_arg(raw_cmd)

            execution = ToolExecution(
                turn_index=turn_index,
                tool_name=tool_name,
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            if tool_name == "apply_patch":
                patch_text = (
                    _as_str(args.get("input"))
                    or _as_str(args.get("patch"))
                    or (_as_str(raw_args) if not args else None)
                )
                if patch_text:
                    _record_patch(patch_text, timestamp, call_id)
            elif tool_name.lower() in _SHELL_TOOL_NAMES:
                shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
                if shell_patch:
                    _record_patch(shell_patch, timestamp, call_id)

        elif item_type == "custom_tool_call":
            activity_since_last_user = True
            tool_name = _as_str(item.get("name")) or "unknown"
            call_id = _as_str(item.get("call_id"))
            raw_input = item.get("input")

            if tool_name == "exec" and isinstance(raw_input, str):
                clean_code = sanitize_unicode(raw_input)
                shell_calls, patch_texts = _extract_codex_exec_js_calls(clean_code)
                exec_key = call_id or f"__anon_exec_{_next_seq()}"
                pending_execs[exec_key] = _PendingCodexExec(
                    call_id=call_id,
                    code=clean_code,
                    turn_index=turn_index,
                    timestamp=timestamp,
                    seq=_next_seq(),
                    expected_cmds=[fmt_cmd for _, fmt_cmd in shell_calls],
                    expected_patches=patch_texts,
                    expected_patch_paths=[_extract_patch_paths(p) for p in patch_texts],
                    matched_cmd_indices=set(),
                    matched_patch_indices=set(),
                )
                open_exec_order.append(exec_key)
                continue

            command = None
            raw_cmd = None
            if tool_name.lower() in _SHELL_TOOL_NAMES:
                if isinstance(raw_input, dict):
                    raw_cmd = raw_input.get("command") or raw_input.get("cmd")
                    command = _format_command_arg(raw_cmd)
                elif isinstance(raw_input, str):
                    command = sanitize_unicode(raw_input)

            execution = ToolExecution(
                turn_index=turn_index,
                tool_name=tool_name,
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            if tool_name == "apply_patch" and isinstance(raw_input, str):
                _record_patch(raw_input, timestamp, call_id)
            elif tool_name.lower() in _SHELL_TOOL_NAMES:
                shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
                if shell_patch:
                    _record_patch(shell_patch, timestamp, call_id)

        elif item_type == "local_shell_call":
            activity_since_last_user = True
            call_id = _as_str(item.get("call_id"))
            action = item.get("action")
            action_dict = action if isinstance(action, dict) else {}
            raw_cmd = action_dict.get("command") or item.get("command")
            command = _format_command_arg(raw_cmd)
            execution = ToolExecution(
                turn_index=turn_index,
                tool_name="local_shell",
                command=command,
                output="",
                exit_code=None,
                is_error=False,
                timestamp=timestamp,
                call_id=call_id,
                seq=_next_seq(),
            )
            tool_executions.append(execution)
            if call_id:
                pending_tools[call_id] = execution

            shell_patch = _extract_patch_from_shell_command(raw_cmd, command)
            if shell_patch:
                _record_patch(shell_patch, timestamp, call_id)

        elif item_type in (
            "function_call_output",
            "custom_tool_call_output",
            "local_shell_call_output",
        ):
            activity_since_last_user = True
            call_id = _as_str(item.get("call_id"))
            explicit_is_error = (
                item.get("is_error") if isinstance(item.get("is_error"), bool) else None
            )
            if call_id and call_id in pending_execs:
                pending_exec = pending_execs.pop(call_id)
                _finalize_exec_call(
                    pending_exec,
                    item.get("output"),
                    explicit_is_error=explicit_is_error,
                    out_timestamp=timestamp,
                )
                continue

            execution = pending_tools.get(call_id) if call_id else None
            is_shell = (
                execution is None
                or execution.tool_name.lower() in _SHELL_TOOL_NAMES
                or execution.tool_name == "apply_patch"
            )
            output_text, exit_code = _unwrap_codex_output(
                item.get("output"),
                is_shell=is_shell and explicit_is_error is not False,
            )
            is_error = explicit_is_error is True
            if exit_code is not None and exit_code != 0:
                is_error = True

            if is_error and call_id:
                failed_call_ids.add(call_id)

            if execution is not None:
                execution.output = output_text
                execution.exit_code = exit_code
                execution.is_error = is_error
                if execution.timestamp is None and timestamp is not None:
                    execution.timestamp = timestamp
            else:
                tool_executions.append(
                    ToolExecution(
                        turn_index=turn_index,
                        tool_name="unknown",
                        command=None,
                        output=output_text,
                        exit_code=exit_code,
                        is_error=is_error,
                        timestamp=timestamp,
                        call_id=call_id,
                        seq=_next_seq(),
                    )
                )

    for leftover_exec in list(pending_execs.values()):
        _finalize_exec_call(
            leftover_exec,
            "",
            explicit_is_error=None,
            out_timestamp=None,
            is_eof_leftover=True,
        )
    pending_execs.clear()

    valid_edits = [
        edit for edit in file_edits if edit.call_id is None or edit.call_id not in failed_call_ids
    ]
    modified_files: list[str] = []
    seen_files: set[str] = set()
    move_by_call_target: dict[tuple[str | None, str | None], list[str]] = {}
    for cid, target_path, src_path in extra_move_paths:
        if cid is None or cid not in failed_call_ids:
            move_by_call_target.setdefault((cid, target_path), []).append(src_path)
    for edit in valid_edits:
        for src_path in move_by_call_target.pop((edit.call_id, edit.path), []):
            _add_modified_file(modified_files, seen_files, src_path)
        for src_path in move_by_call_target.pop((edit.call_id, None), []):
            _add_modified_file(modified_files, seen_files, src_path)
        _add_modified_file(modified_files, seen_files, edit.path)
    for remaining in move_by_call_target.values():
        for src_path in remaining:
            _add_modified_file(modified_files, seen_files, src_path)

    return ParsedTranscript(
        format="codex",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=valid_edits,
        modified_files=modified_files,
    )


def parse_generic_records(
    records: Sequence[dict[str, Any]],
    *,
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse generic flat JSONL transcripts."""
    detected_session_id = session_id
    user_turns: list[UserTurn] = []
    tool_executions: list[ToolExecution] = []
    file_edits: list[FileEdit] = []
    modified_files: list[str] = []
    seen_files: set[str] = set()

    turn_index = 0
    seq = 0

    def _next_seq() -> int:
        nonlocal seq
        seq += 1
        return seq

    for record in records:
        if detected_session_id is None:
            sid = _as_str(record.get("session_id")) or _as_str(record.get("sessionId"))
            if sid:
                detected_session_id = sid

        timestamp = _as_str(record.get("timestamp"))
        rec_type = _as_str(record.get("type"))
        role = _as_str(record.get("role"))

        if rec_type == "file_edit":
            path = _as_str(record.get("path")) or _as_str(record.get("file_path"))
            if not path:
                continue
            raw_op = _as_str(record.get("operation")) or "edit"
            op: FileOperation = raw_op if raw_op in VALID_FILE_OPERATIONS else "edit"  # type: ignore[assignment]
            edit = FileEdit(
                turn_index=turn_index,
                path=path,
                operation=op,
                old_text=_as_str(record.get("old_text")) or _as_str(record.get("old_string")),
                new_text=_as_str(record.get("new_text")) or _as_str(record.get("new_string")),
                timestamp=timestamp,
                call_id=_as_str(record.get("call_id")),
                seq=_next_seq(),
            )
            file_edits.append(edit)
            _add_modified_file(modified_files, seen_files, path)
            continue

        if role == "user" or (rec_type == "user" and role is None):
            raw_content = record.get("content")
            if raw_content is None:
                raw_content = record.get("text")
            text = _extract_text_from_content(raw_content).strip()
            if text:
                turn_index += 1
                user_turns.append(
                    UserTurn(
                        turn_index=turn_index,
                        text=text,
                        timestamp=timestamp,
                        source="generic",
                        seq=_next_seq(),
                    )
                )
            continue

        is_tool_record = (
            role == "tool"
            or rec_type in ("tool", "tool_execution", "command", "bash", "shell")
            or "command" in record
        )
        if is_tool_record:
            tool_name = (
                _as_str(record.get("tool_name"))
                or _as_str(record.get("name"))
                or (rec_type if rec_type in ("bash", "shell") else "shell")
            )
            command = _format_command_arg(record.get("command") or record.get("cmd"))
            output_val = record.get("output")
            if output_val is not None:
                output_text = _extract_text_from_content(output_val)
            else:
                stdout = _as_str(record.get("stdout")) or ""
                stderr = _as_str(record.get("stderr")) or ""
                if stdout or stderr:
                    output_text = "\n".join(part for part in (stdout, stderr) if part)
                else:
                    output_text = _extract_text_from_content(record.get("content"))

            explicit_is_error = (
                record.get("is_error") if isinstance(record.get("is_error"), bool) else None
            )
            exit_code = _as_int(record.get("exit_code"))
            if exit_code is None:
                exit_code = _as_int(record.get("exitCode"))
            is_shell = tool_name.lower() in _SHELL_TOOL_NAMES or command is not None
            if exit_code is None and is_shell and explicit_is_error is not False:
                exit_code = _extract_exit_code_from_first_line(output_text)

            is_error = explicit_is_error is True
            if exit_code is not None and exit_code != 0:
                is_error = True

            tool_executions.append(
                ToolExecution(
                    turn_index=turn_index,
                    tool_name=tool_name,
                    command=command,
                    output=output_text,
                    exit_code=exit_code,
                    is_error=is_error,
                    timestamp=timestamp,
                    call_id=_as_str(record.get("call_id")) or _as_str(record.get("id")),
                    seq=_next_seq(),
                )
            )

    return ParsedTranscript(
        format="generic",
        session_id=detected_session_id,
        user_turns=user_turns,
        tool_executions=tool_executions,
        file_edits=file_edits,
        modified_files=modified_files,
    )


def parse_transcript_lines(
    lines: Iterable[str],
    *,
    fmt: str = "auto",
    session_id: str | None = None,
) -> ParsedTranscript:
    """Parse transcript JSONL lines using auto-detection or an explicit format."""
    if fmt not in SUPPORTED_FORMATS:
        raise ValueError(
            f"Unsupported transcript format {fmt!r}; expected one of {sorted(SUPPORTED_FORMATS)}"
        )

    records = _iter_json_records(lines)
    if not records:
        return ParsedTranscript(
            format="unknown" if fmt == "auto" else fmt,
            session_id=session_id,
        )

    resolved_fmt = detect_transcript_format(records) if fmt == "auto" else fmt
    if resolved_fmt == "claude-code":
        return parse_claude_code_records(records, session_id=session_id)
    if resolved_fmt == "codex":
        return parse_codex_records(records, session_id=session_id)
    return parse_generic_records(records, session_id=session_id)


def parse_transcript(
    path: str | Path,
    *,
    fmt: str = "auto",
    session_id: str | None = None,
) -> ParsedTranscript:
    """Read and parse a JSONL transcript file from disk."""
    transcript_path = Path(path)
    with transcript_path.open("r", encoding="utf-8", errors="replace") as handle:
        return parse_transcript_lines(handle, fmt=fmt, session_id=session_id)
